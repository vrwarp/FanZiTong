/**
 * What a component contributes to the meaning of the character it sits in.
 *
 * These are the Kangxi radicals and their squeezed writing forms (水 → 氵,
 * 食 → 飠, 手 → 扌), glossed for someone who is meeting them as *reading*
 * cues rather than as dictionary lookup keys: not "radical 85" but "water —
 * liquids, and anything done with them".
 *
 * Two deliberate omissions.
 *
 * First, the pure shape-atoms — 丿, 冂, 彐, 爻 and their kind — have no entry.
 * They are strokes that a decomposition algorithm can name but that tell a
 * reader nothing, and 肉 "is 冂 plus 仌" is worse than silence. Absence here is
 * what stops the app from saying it: a breakdown is only shown when at least
 * one of its parts is glossed here or carries the reading.
 *
 * Second, nothing here is a claim about where the character came from. It is a
 * claim about how the writing system files it, which is the part that helps
 * you guess what an unfamiliar character is about. The history is on 字源.
 */

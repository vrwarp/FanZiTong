export const STARTER_ENTRIES: Record<Exclude<DomainCategory, 'custom'>, SeedEntry[]> = {
  food: FOOD,
  church: CHURCH,
  slang: SLANG,
  anime: ANIME,
};

export interface BuildStarterDeckOptions {
  now?: Date;
  idFactory?: () => string;
}

/** Materialize the starter deck as brand-new (state 0) cards. */
export function buildStarterDeck(options: BuildStarterDeckOptions = {}): VocabCard[] {
  const now = options.now ?? new Date();
  const makeId = options.idFactory ?? uuid;
  const cards: VocabCard[] = [];
  let index = 0;
  for (const domain of Object.keys(STARTER_ENTRIES) as (keyof typeof STARTER_ENTRIES)[]) {
    for (const [
      traditional,
      pinyin,
      definition,
      tags,
      sentence,
      sentencePinyin,
      translation,
      foils,
    ] of STARTER_ENTRIES[domain]) {
      // Stagger createdAt so the new-card queue keeps authoring order.
      const createdAt = new Date(now.getTime() + index).toISOString();
      index += 1;
      cards.push({
        id: makeId(),
        traditional,
        pinyin,
        definition,
        domain,
        tags: tags.split('|').filter(Boolean),
        exampleSentenceTraditional: sentence,
        exampleSentencePinyin: sentencePinyin,
        exampleSentenceTranslation: translation,
        visualFoils: foils.split('|').filter(Boolean),
        fsrs: newFsrsState(now),
        createdAt,
        updatedAt: createdAt,
      });
    }
  }
  return cards;
}

export const STARTER_DECK_SIZE = Object.values(STARTER_ENTRIES).reduce(
  (sum, entries) => sum + entries.length,
  0,
);
